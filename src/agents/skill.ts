import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { type Config, loadConfig } from "../config/config.ts";
import { spawnRunner } from "../herdr/bridge.ts";
import { guide } from "./guide.ts";

export const SKILL_REL = ".claude/skills/agt/SKILL.md";
export const SKILL_EXCLUDE = "/.claude/skills/agt/";
export const MARKER = "<!-- Generated by agt; do not edit. Regenerated by agt init, agt setup and agt start. -->";

const FRONTMATTER = [
  "---",
  "name: agt",
  "description: Use when working in an AgentThread project (AGT_ROLE is set, or the project has .agentthread/) — how to use the agt CLI for your role (main, coordinator or worker): threads, tickets, workers, notes, questions, handoffs and recovery.",
  "---",
].join("\n");

type Env = Record<string, string | undefined>;
type Opts = { root: string; config: Config };

/** The skill file: frontmatter, the generated marker, then the guide for every role. */
export function skillText(o: Opts): string {
  return `${FRONTMATTER}\n${MARKER}\n\n${guide({ role: "all", root: o.root, config: o.config })}`;
}

/**
 * Writes `<dir>/.claude/skills/agt/SKILL.md` when it is ours to write: not tracked, and either absent or carrying the
 * marker line. Rewrites only when the content differs. Does nothing when `agents.skill` is false.
 */
export function writeSkill(
  dir: string,
  o: Opts & { tracked: boolean; log: (message: string) => void },
): "written" | "unchanged" | "skipped" {
  if (o.config.agents.skill === false) return "skipped";
  const file = join(dir, SKILL_REL);
  const current = existsSync(file) ? readFileSync(file, "utf8") : undefined;
  if (o.tracked || (current !== undefined && !current.split("\n").some((l) => l.replace(/\r$/, "") === MARKER))) {
    o.log(`agt: ${SKILL_REL} is not generated by agt; leaving it alone`);
    return "skipped";
  }
  const text = skillText(o);
  if (current === text) return "unchanged";
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
  return "written";
}

/**
 * agt init / setup / start: the skill in the project root, hidden through the main repository's info/exclude (the
 * common dir, which covers every worktree too). Synchronous: CLI paths only; the daemon writes worktree skills through
 * writeAgentsFilesAsync. Never throws.
 */
export function refreshRootSkill(root: string, env: Env = process.env, log: (message: string) => void = (m) => console.error(m)): void {
  try {
    const config = loadConfig(root, env);
    if (config.agents.skill === false) return;
    const git = (...args: string[]) => spawnRunner("git", ["-C", root, ...args], env, 5000);
    const common = git("rev-parse", "--git-common-dir");
    if (common.exitCode !== 0 || !common.stdout.trim()) return;
    const tracked = git("ls-files", "--error-unmatch", "--", SKILL_REL).exitCode === 0;
    if (writeSkill(root, { root, config, tracked, log }) === "skipped") return;
    const info = join(resolve(root, common.stdout.trim()), "info", "exclude");
    const text = existsSync(info) ? readFileSync(info, "utf8") : "";
    if (text.split("\n").some((l) => l.replace(/\r$/, "") === SKILL_EXCLUDE)) return;
    mkdirSync(dirname(info), { recursive: true });
    writeFileSync(info, `${text}${text && !text.endsWith("\n") ? "\n" : ""}${SKILL_EXCLUDE}\n`);
  } catch (e) {
    log(`agt: writing ${SKILL_REL} failed: ${e instanceof Error ? e.message : String(e)}`);
  }
}
