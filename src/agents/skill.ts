import { existsSync, mkdirSync, readFileSync, rmdirSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { type Config, loadConfig } from "../config/config.ts";
import { spawnRunner } from "../herdr/bridge.ts";
import { workspaceReposNoSpawn } from "../project/workspace.ts";
import { FEATURE_WORKFLOW, MANAGE_DOCS, TEMPLATES } from "../workflow/index.ts";
import { projectConfigSection } from "../workflow/project-config.ts";
import { guide } from "./guide.ts";

export const SKILL_REL = ".claude/skills/agt/SKILL.md";
export const MARKER = "<!-- Generated by agt; do not edit. Regenerated by agt init, agt setup and agt start. -->";
/** Every generated skill is written under both: Claude Code (and omp, OpenCode) read the first, Codex the second. */
export const SKILL_ROOTS = [".claude/skills", ".agents/skills"] as const;

const FRONTMATTER = [
  "---",
  "name: agt",
  "description: \"Use when working in an AgentThread project (AGT_ROLE is set, or the project has .agentthread/) — how to use the agt CLI for your role (main, coordinator or worker): threads, tickets, workers, notes, questions, handoffs and recovery.\"",
  "---",
].join("\n");

type Env = Record<string, string | undefined>;
/** `task`: a task thread's task name; its generated skills have `{task}` in the project config filled in. */
type Opts = { root: string; config: Config; task?: string };

/** The skill file: frontmatter, the generated marker, then the guide for every role. */
export function skillText(o: Opts): string {
  return `${FRONTMATTER}\n${MARKER}\n\n${guide({ role: "all", root: o.root, config: o.config })}`;
}

/** A skill's Markdown with the marker line right after its frontmatter. */
function withMarker(md: string): string {
  const end = md.indexOf("\n---\n", 4) + "\n---\n".length;
  return `${md.slice(0, end)}${MARKER}\n${md.slice(end)}`;
}

/** The feature-workflow skill: the shipped content, then the project config section rendered from agt config. */
export function featureWorkflowText(o: Opts): string {
  const repos = Object.entries(workspaceReposNoSpawn(o.root, o.config)).map(([name, r]) => ({ name, path: r.path }));
  return `${withMarker(FEATURE_WORKFLOW)}\n\n${projectConfigSection(o.config, repos, o.task)}`;
}

const NOT_CONFIGURED = "not configured";
const COMMIT_POLICY = " — the coordinator commits its own .docs changes, one commit per logical change, and never pushes";

/** The doc-rules skill: the shipped template with its placeholders filled from agt config. */
export function manageDocsText(o: Opts): string {
  const names = Object.keys(workspaceReposNoSpawn(o.root, o.config));
  const w = o.config.workflow;
  const fill: Record<string, string> = {
    REPOS: names.length ? names.join(", ") : NOT_CONFIGURED,
    LANGUAGE: w.file_language,
    REPORT_BACK: ` (the worker reports "${w.report_words.done}" when the ticket is done, or "${w.report_words.blocked}" with the reason when it cannot go on)`,
    COMMIT_POLICY,
  };
  return withMarker(MANAGE_DOCS).replace(/\{\{([A-Z_]+)\}\}/g, (all, key: string) => fill[key] ?? all);
}

/** The generated skills: each a name and its files (relative to the skill's folder). */
const SKILLS: { name: string; files: { rel: string; text: (o: Opts) => string }[] }[] = [
  { name: "agt", files: [{ rel: "SKILL.md", text: skillText }] },
  {
    name: "agt-feature-workflow",
    files: [
      { rel: "SKILL.md", text: featureWorkflowText },
      ...(["spec", "ticket", "release"] as const).map((t) => ({ rel: `templates/${t}.md`, text: () => `${MARKER}\n${TEMPLATES[t]}` })),
    ],
  },
  { name: "manage-docs", files: [{ rel: "SKILL.md", text: manageDocsText }] },
];

/** Every file of a skill, under both roots, relative to the project (or thread dir, or worktree). */
const relsOf = (skill: (typeof SKILLS)[number]) => SKILL_ROOTS.flatMap((r) => skill.files.map((f) => `${r}/${skill.name}/${f.rel}`));
export const GENERATED_RELS: string[] = SKILLS.flatMap(relsOf);
/** The exclude line for a generated file whose project sits `prefix` below the repository top (`git rev-parse --show-prefix`). */
export const skillExclude = (prefix = "", rel = SKILL_REL) => `/${prefix}${rel}`;
export const SKILL_EXCLUDES: string[] = GENERATED_RELS.map((rel) => skillExclude("", rel));

const hasMarker = (text: string) => text.split("\n").some((l) => l.replace(/\r$/, "") === MARKER);

/** The first file of `skill` in `dir` that is the project's own (tracked, or present without the marker). */
function ownedFile(dir: string, skill: (typeof SKILLS)[number], tracked: ReadonlySet<string>): string | undefined {
  return relsOf(skill).find((rel) => {
    if (tracked.has(rel)) return true;
    const file = join(dir, rel);
    return existsSync(file) && !hasMarker(readFileSync(file, "utf8"));
  });
}

/** The generated files in `dir` that are ours to hide: those of every skill the project does not own there. */
export function generatedExcludes(dir: string, tracked: ReadonlySet<string> = new Set()): string[] {
  return SKILLS.filter((s) => !ownedFile(dir, s, tracked)).flatMap(relsOf);
}

/** Removes the files of `skill` in `dir` that carry the marker (a copy agt wrote), then the folders they leave empty. */
function removeGenerated(dir: string, skill: (typeof SKILLS)[number]): void {
  for (const rel of relsOf(skill)) {
    const file = join(dir, rel);
    if (existsSync(file) && hasMarker(readFileSync(file, "utf8"))) unlinkSync(file);
  }
  for (const r of SKILL_ROOTS) {
    const top = join(dir, r, skill.name);
    for (const d of [...new Set(skill.files.map((f) => dirname(join(top, f.rel))))].sort().reverse().concat(top)) {
      try {
        rmdirSync(d);
      } catch {}
    }
  }
}

/**
 * Writes every generated skill into `dir`, under both skill roots, when it is ours to write: a skill any of whose files
 * is tracked or carries no marker is the project's own and is kept as it is (logged), everywhere. A skill the workspace
 * root owns (a file of it under the root without the marker) is the project's own in every thread dir and worktree too:
 * nothing is written there and a copy agt wrote earlier is removed. A file is rewritten only when its content differs.
 * Does nothing when `agents.skill` is false.
 */
export function writeSkills(
  dir: string,
  o: Opts & { tracked: ReadonlySet<string>; log: (message: string) => void },
): Record<string, "written" | "unchanged" | "kept" | "off"> {
  const out: Record<string, "written" | "unchanged" | "kept" | "off"> = {};
  if (o.config.agents.skill === false) return Object.fromEntries(SKILLS.map((s) => [s.name, "off"]));
  for (const skill of SKILLS) {
    const owned = ownedFile(dir, skill, o.tracked);
    if (owned) {
      o.log(`kept the project's own skill ${skill.name} at ${join(dir, owned)}`);
      out[skill.name] = "kept";
      continue;
    }
    const rootOwned = resolve(dir) === resolve(o.root) ? undefined : ownedFile(o.root, skill, new Set());
    if (rootOwned) {
      removeGenerated(dir, skill);
      o.log(`kept the project's own skill ${skill.name} at ${join(o.root, rootOwned)}`);
      out[skill.name] = "kept";
      continue;
    }
    out[skill.name] = "unchanged";
    for (const f of skill.files) {
      const text = f.text(o);
      for (const r of SKILL_ROOTS) {
        const file = join(dir, r, skill.name, f.rel);
        if (existsSync(file) && readFileSync(file, "utf8") === text) continue;
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, text);
        out[skill.name] = "written";
      }
    }
  }
  return out;
}

/**
 * agt init / setup / start: the skills in the project root, hidden through the main repository's info/exclude (the
 * common dir, which covers every worktree too). Synchronous: CLI paths only; the daemon writes worktree skills through
 * writeAgentsFilesAsync. `log` (default: stderr) hears the skills kept as the project's own. Never throws.
 */
export function refreshRootSkill(root: string, env: Env = process.env, log: (message: string) => void = (m) => console.error(m)): void {
  try {
    const config = loadConfig(root, env);
    if (config.agents.skill === false) return;
    const git = (...args: string[]) => spawnRunner("git", ["-C", root, ...args], env, 5000);
    const common = git("rev-parse", "--git-common-dir");
    if (common.exitCode !== 0 || !common.stdout.trim()) {
      // a root outside git gets no generated skills; the ones it owns are still named
      for (const skill of SKILLS) {
        const owned = ownedFile(root, skill, new Set());
        if (owned) log(`kept the project's own skill ${skill.name} at ${join(root, owned)}`);
      }
      return;
    }
    const listed = git("ls-files", "--", ...SKILL_ROOTS);
    const tracked = new Set(listed.exitCode === 0 ? excludeLinesOf(listed.stdout).filter(Boolean) : []);
    const prefix = git("rev-parse", "--show-prefix");
    const pre = prefix.exitCode === 0 ? prefix.stdout.trim() : "";
    const info = join(resolve(root, common.stdout.trim()), "info", "exclude");
    const ours = new Set(generatedExcludes(root, tracked));
    // the excludes first, so the files are never visible; and only while the files are ours
    for (const rel of GENERATED_RELS) {
      if (ours.has(rel)) addExcludeLine(info, skillExclude(pre, rel));
      else removeExcludeLine(info, skillExclude(pre, rel));
    }
    writeSkills(root, { root, config, tracked, log });
  } catch (e) {
    log(`agt: writing the generated skills failed: ${e instanceof Error ? e.message : String(e)}`);
  }
}

const excludeLinesOf = (text: string) => text.split("\n").map((l) => l.replace(/\r$/, ""));

function addExcludeLine(info: string, line: string): void {
  const text = existsSync(info) ? readFileSync(info, "utf8") : "";
  if (excludeLinesOf(text).includes(line)) return;
  mkdirSync(dirname(info), { recursive: true });
  writeFileSync(info, `${text}${text && !text.endsWith("\n") ? "\n" : ""}${line}\n`);
}

function removeExcludeLine(info: string, line: string): void {
  if (!existsSync(info)) return;
  const text = readFileSync(info, "utf8");
  const all = text.split("\n");
  const kept = all.filter((l) => l.replace(/\r$/, "") !== line);
  if (kept.length !== all.length) writeFileSync(info, kept.join("\n"));
}
