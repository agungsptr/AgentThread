import type { GitTrail } from "../project/gittrail.ts";
import type { Session, Thread } from "../state/projection.ts";
import { clampHeadings, oneLine } from "./markdown.ts";

const MAX_BYTES = 16384;
const TRUNC = "_(truncated — see sub.thread.md)_";

const cap = (s: string, n: number) => (s.length > n ? `${s.slice(0, n - 1)}…` : s);
const entry = (d: { ts: string; message: string }) => cap(`- ${d.ts} ${oneLine(d.message)}`, 300);
const orNone = (lines: string[], none: string) => (lines.length ? lines : [none]);

interface Limits {
  handoff: number;
  decisions: number;
  findings: number;
  board: number;
  goal: number;
  criteria: number;
}
const LEVELS: Limits[] = [
  { handoff: 6000, decisions: 20, findings: 20, board: 40, goal: 2000, criteria: 20 },
  { handoff: 1500, decisions: 20, findings: 20, board: 40, goal: 2000, criteria: 20 },
  { handoff: 0, decisions: 20, findings: 20, board: 40, goal: 2000, criteria: 20 },
  { handoff: 0, decisions: 5, findings: 20, board: 40, goal: 2000, criteria: 20 },
  { handoff: 0, decisions: 0, findings: 20, board: 40, goal: 2000, criteria: 20 },
  { handoff: 0, decisions: 0, findings: 5, board: 40, goal: 2000, criteria: 20 },
  { handoff: 0, decisions: 0, findings: 0, board: 40, goal: 2000, criteria: 20 },
  { handoff: 0, decisions: 0, findings: 0, board: 10, goal: 2000, criteria: 20 },
  { handoff: 0, decisions: 0, findings: 0, board: 0, goal: 2000, criteria: 20 },
  { handoff: 0, decisions: 0, findings: 0, board: 0, goal: 500, criteria: 5 },
];

export function renderBrief(o: { thread: Thread; sessions?: Session[]; trail?: GitTrail; dir?: string }): string {
  let md = "";
  for (const lim of LEVELS) {
    md = build(o.thread, o.trail, lim);
    if (Buffer.byteLength(md) < MAX_BYTES) break;
  }
  return md;
}

function build(t: Thread, trail: GitTrail | undefined, lim: Limits): string {
  const full = LEVELS[0]!;
  let handoff: string[];
  if (!t.handoff) handoff = ["None yet."];
  else {
    const body = clampHeadings(t.handoff.content.trim());
    handoff = [
      ...(t.handoff.generated ? ["> Generated by the daemon.", ""] : []),
      ...(lim.handoff === 0 ? [TRUNC] : body.length > lim.handoff ? [clampHeadings(body.slice(0, lim.handoff)), "", TRUNC] : [body]),
    ];
  }
  const boardAll = t.tickets.map(
    (k) =>
      cap(
        `- ${k.id} [${k.status}] ${oneLine(k.title)} — scope: ${k.scope.join(", ")}${k.assignee ? ` (assignee: ${k.assignee.slice(0, 8)})` : ""}`,
        300,
      ),
  );
  const board =
    boardAll.length <= lim.board
      ? boardAll
      : lim.board < full.board
        ? [...boardAll.slice(0, lim.board), TRUNC]
        : [...boardAll.slice(0, lim.board), `… ${boardAll.length - lim.board} more tickets (see board.md)`];
  const tail = <T>(xs: T[], n: number) => (n === 0 ? [] : xs.slice(-n));
  const findings = tail(t.findings, lim.findings).map(entry);
  const decisions = tail(t.decisions, lim.decisions).map(entry);
  const questions = t.questions.slice(-20).map(entry);
  const earlier = t.questions.length - questions.length;
  const goal = clampHeadings(t.goal.trim());
  const criteria = t.criteria.slice(0, lim.criteria).map((c) => cap(`- [ ] ${oneLine(c)}`, 300));
  const commits = trail?.commits.slice(0, 20) ?? [];
  const noTrail = !trail && t.status !== "done";
  return [
    `# Brief — thread ${t.id}: ${oneLine(t.title)}`,
    "",
    "## Where things stand",
    "",
    `Status: ${t.status}`,
    t.progress ? `Latest progress: ${t.progress.ts} ${cap(oneLine(t.progress.message), 1000)}` : "No progress recorded yet.",
    "",
    "## Goal",
    "",
    (goal.length > lim.goal ? `${clampHeadings(goal.slice(0, lim.goal))}\n\n${TRUNC}` : goal) || "_Not set._",
    "",
    "## Acceptance criteria",
    "",
    ...orNone(criteria, "_None yet._"),
    ...(t.criteria.length > lim.criteria ? [lim.criteria < full.criteria ? TRUNC : `… ${t.criteria.length - lim.criteria} more`] : []),
    "",
    "## Board",
    "",
    ...orNone(board, "None yet."),
    "",
    "## Findings",
    "",
    ...orNone(findings, "None yet."),
    ...(lim.findings < full.findings && t.findings.length > lim.findings ? [TRUNC] : []),
    "",
    "## Open questions",
    "",
    ...(earlier > 0 ? [`… ${earlier} earlier`] : []),
    ...orNone(questions, "None yet."),
    "",
    "## Decisions",
    "",
    ...orNone(decisions, "None yet."),
    ...(lim.decisions < full.decisions && t.decisions.length > lim.decisions ? [TRUNC] : []),
    "",
    "## Handoff",
    "",
    ...handoff,
    "",
    "## Git trail",
    "",
    ...(noTrail ? ["Git trail unavailable."] : commits.length ? commits.map((c) => cap(`- ${oneLine(c)}`, 300)) : ["No commits on this thread yet."]),
    ...(trail?.diffStat ? ["", `Uncommitted: ${oneLine(trail.diffStat)}`] : []),
    ...(trail && trail.untracked > 0 ? [...(trail.diffStat ? [] : [""]), `Untracked files: ${trail.untracked}`] : []),
    "",
    "## How to continue",
    "",
    "1. Read AGENTS.md in your working directory for your role's rules.",
    "2. Check the board and progress above; continue from the latest progress.",
    '3. Record progress with agt progress <id> "<…>", findings with agt note, doubts with agt question.',
    "",
  ].join("\n");
}
