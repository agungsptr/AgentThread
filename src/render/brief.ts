import type { GitTrail } from "../project/gittrail.ts";
import { progressBy, type Session, type Thread } from "../state/projection.ts";
import { DEFAULT_CONFIG, type Config } from "../config/config.ts";
import { clampHeadings, oneLine, tierLines } from "./markdown.ts";

const MAX_BYTES = 16384;
const TRUNC = "_(truncated — see sub.thread.md)_";

/** Cut `s` to at most `maxBytes` UTF-8 bytes (on a character boundary), ending with `…` when cut. */
export function capBytes(s: string, maxBytes: number): string {
  if (Buffer.byteLength(s) <= maxBytes) return s;
  if (maxBytes < 3) return "";
  const room = maxBytes - 3; // "…" is 3 bytes
  let out = "";
  let used = 0;
  for (const ch of s) {
    const n = Buffer.byteLength(ch);
    if (used + n > room) break;
    out += ch;
    used += n;
  }
  return `${out}…`;
}
const entry = (d: { ts: string; message: string }) => capBytes(`- ${d.ts} ${oneLine(d.message)}`, 300);
const orNone = (lines: string[], none: string) => (lines.length ? lines : [none]);

interface Limits {
  handoff: number;
  decisions: number;
  findings: number;
  board: number;
  goal: number;
  criteria: number;
  open: number;
  answered: number;
  title: number;
}
const LEVELS: Limits[] = [
  { handoff: 6000, decisions: 20, findings: 20, board: 40, goal: 2000, criteria: 20, open: 20, answered: 10, title: 1000 },
  { handoff: 1500, decisions: 20, findings: 20, board: 40, goal: 2000, criteria: 20, open: 20, answered: 10, title: 1000 },
  { handoff: 0, decisions: 20, findings: 20, board: 40, goal: 2000, criteria: 20, open: 20, answered: 10, title: 1000 },
  { handoff: 0, decisions: 5, findings: 20, board: 40, goal: 2000, criteria: 20, open: 20, answered: 10, title: 1000 },
  { handoff: 0, decisions: 0, findings: 20, board: 40, goal: 2000, criteria: 20, open: 20, answered: 10, title: 1000 },
  { handoff: 0, decisions: 0, findings: 5, board: 40, goal: 2000, criteria: 20, open: 20, answered: 10, title: 1000 },
  { handoff: 0, decisions: 0, findings: 0, board: 40, goal: 2000, criteria: 20, open: 20, answered: 10, title: 1000 },
  { handoff: 0, decisions: 0, findings: 0, board: 10, goal: 2000, criteria: 20, open: 20, answered: 10, title: 1000 },
  { handoff: 0, decisions: 0, findings: 0, board: 0, goal: 2000, criteria: 20, open: 20, answered: 10, title: 1000 },
  { handoff: 0, decisions: 0, findings: 0, board: 0, goal: 500, criteria: 5, open: 20, answered: 10, title: 1000 },
  { handoff: 0, decisions: 0, findings: 0, board: 0, goal: 500, criteria: 5, open: 20, answered: 3, title: 1000 },
  { handoff: 0, decisions: 0, findings: 0, board: 0, goal: 500, criteria: 5, open: 20, answered: 0, title: 1000 },
  { handoff: 0, decisions: 0, findings: 0, board: 0, goal: 500, criteria: 5, open: 5, answered: 0, title: 1000 },
  { handoff: 0, decisions: 0, findings: 0, board: 0, goal: 500, criteria: 5, open: 5, answered: 0, title: 200 },
];

export function renderBrief(o: { thread: Thread; sessions?: Session[]; trail?: GitTrail; dir?: string; config?: Config }): string {
  let md = "";
  const tier = tierLines(o.thread, o.sessions ?? [], o.config ?? DEFAULT_CONFIG);
  for (const lim of LEVELS) {
    md = build(o.thread, o.trail, lim, tier);
    if (Buffer.byteLength(md) < MAX_BYTES) return md;
  }
  // Last resort: the bound holds even if every level overflows.
  return capBytes(md, MAX_BYTES - 1);
}

function build(t: Thread, trail: GitTrail | undefined, lim: Limits, tier: string[]): string {
  const full = LEVELS[0]!;
  let handoff: string[];
  if (!t.handoff) handoff = ["None yet."];
  else {
    const body = clampHeadings(t.handoff.content.trim());
    handoff = [
      ...(t.handoff.generated ? ["> Generated by the daemon.", ""] : []),
      `Written ${t.handoff.ts} by ${t.handoff.by}`,
      "",
      ...(lim.handoff === 0 ? [TRUNC] : Buffer.byteLength(body) > lim.handoff ? [clampHeadings(capBytes(body, lim.handoff)), "", TRUNC] : [body]),
    ];
  }
  const boardAll = t.tickets.map((k) => {
    const line = capBytes(
      `- ${k.id} [${k.status}] ${oneLine(k.title)} — scope: ${k.scope.join(", ")}${k.assignee ? ` (assignee: ${k.assignee.slice(0, 8)})` : ""}`,
      300,
    );
    const p = t.workerProgress[k.id];
    return p ? `${line}\n${capBytes(`  - progress ${p.ts} ${progressBy(p)} ${oneLine(p.message)}`, 300)}` : line;
  });
  const board =
    boardAll.length <= lim.board
      ? boardAll
      : lim.board < full.board
        ? [...boardAll.slice(0, lim.board), TRUNC]
        : [...boardAll.slice(0, lim.board), `… ${boardAll.length - lim.board} more tickets (see board.md)`];
  const tail = <T>(xs: T[], n: number) => (n === 0 ? [] : xs.slice(-n));
  const findings = tail(t.findings, lim.findings).map(entry);
  const decisions = tail(t.decisions, lim.decisions).map(entry);
  const openQs = t.questions.filter((q) => !q.answer);
  const questions = (lim.open === 0 ? [] : openQs.slice(-lim.open)).map((q) => entry({ ts: q.ts, message: `(${q.id}) ${q.message}` }));
  const earlier = openQs.length - questions.length;
  const answered = t.questions.filter((q) => q.answer).slice(lim.answered === 0 ? Infinity : -lim.answered).map((q) => capBytes(`- ${q.id} ${oneLine(q.message)} — answer: ${oneLine(q.answer!.message)}`, 300));
  const goal = clampHeadings(t.goal.trim());
  const criteria = t.criteria.slice(0, lim.criteria).map((c) => capBytes(`- [ ] ${oneLine(c)}`, 300));
  const commits = trail?.commits.slice(0, 20) ?? [];
  const noTrail = !trail && t.status !== "done";
  return [
    `# Brief — thread ${t.id}: ${capBytes(oneLine(t.title), lim.title)}`,
    "",
    "## Where things stand",
    "",
    `Status: ${t.status}`,
    ...tier,
    t.progress ? `Latest progress: ${t.progress.ts} ${progressBy(t.progress)} ${capBytes(oneLine(t.progress.message), 1000)}` : "No progress recorded yet.",
    "",
    "## Goal",
    "",
    (Buffer.byteLength(goal) > lim.goal ? `${clampHeadings(capBytes(goal, lim.goal))}\n\n${TRUNC}` : goal) || "_Not set._",
    "",
    "## Acceptance criteria",
    "",
    ...orNone(criteria, "_None yet._"),
    ...(t.criteria.length > lim.criteria ? [lim.criteria < full.criteria ? TRUNC : `… ${t.criteria.length - lim.criteria} more`] : []),
    "",
    "## Board",
    "",
    ...orNone(board, "None yet."),
    "",
    "## Findings",
    "",
    ...orNone(findings, "None yet."),
    ...(lim.findings < full.findings && t.findings.length > lim.findings ? [TRUNC] : []),
    "",
    "## Open questions",
    "",
    ...(earlier > 0 ? [`… ${earlier} earlier`] : []),
    ...orNone(questions, "None yet."),
    "",
    "## Decisions",
    "",
    ...orNone(decisions, "None yet."),
    ...(lim.decisions < full.decisions && t.decisions.length > lim.decisions ? [TRUNC] : []),
    "",
    ...(answered.length ? ["## Answered questions", "", ...answered, ""] : []),
    "## Handoff",
    "",
    ...handoff,
    "",
    "## Git trail",
    "",
    ...(noTrail ? ["Git trail unavailable."] : commits.length ? commits.map((c) => capBytes(`- ${oneLine(c)}`, 300)) : ["No commits on this thread yet."]),
    ...(trail?.diffStat ? ["", `Uncommitted: ${oneLine(trail.diffStat)}`] : []),
    ...(trail && trail.untracked > 0 ? [...(trail.diffStat ? [] : [""]), `Untracked files: ${trail.untracked}`] : []),
    "",
    "## How to continue",
    "",
    "1. Read AGENTS.md in your working directory for your role's rules.",
    "2. Check the board and progress above; continue from the latest progress.",
    `3. Record progress with agt progress ${t.id} "<…>", findings with agt note ${t.id}, doubts with agt question ${t.id}.`,
    "",
  ].join("\n");
}
