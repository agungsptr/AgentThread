import type { GitTrail } from "../project/gittrail.ts";
import type { Session, Thread } from "../state/projection.ts";
import { clampHeadings, oneLine } from "./markdown.ts";

const entries = (es: Thread["findings"]) => es.map((d) => `- ${d.ts} ${oneLine(d.message)}`);
const orNone = (lines: string[], none: string) => (lines.length ? lines : [none]);

export function renderBrief(o: { thread: Thread; sessions: Session[]; trail?: GitTrail; dir: string }): string {
  const t = o.thread;
  const handoff = t.handoff
    ? [...(t.handoff.generated ? ["> Generated by the daemon.", ""] : []), clampHeadings(t.handoff.content.trim())]
    : ["None yet."];
  const board = t.tickets.map(
    (k) =>
      `- ${k.id} [${k.status}] ${oneLine(k.title)} — scope: ${k.scope.join(", ")}${k.assignee ? ` (assignee: ${k.assignee.slice(0, 8)})` : ""}`,
  );
  const commits = o.trail?.commits.slice(0, 20) ?? [];
  return [
    `# Brief — thread ${t.id}: ${oneLine(t.title)}`,
    "",
    "## Where things stand",
    "",
    `Status: ${t.status}`,
    t.progress ? `Latest progress: ${t.progress.ts} ${oneLine(t.progress.message)}` : "No progress recorded yet.",
    "",
    "## Goal",
    "",
    clampHeadings(t.goal.trim()) || "_Not set._",
    "",
    "## Acceptance criteria",
    "",
    ...orNone(t.criteria.map((c) => `- [ ] ${oneLine(c)}`), "_None yet._"),
    "",
    "## Board",
    "",
    ...orNone(board, "None yet."),
    "",
    "## Findings",
    "",
    ...orNone(entries(t.findings.slice(-20)), "None yet."),
    "",
    "## Open questions",
    "",
    ...orNone(entries(t.questions), "None yet."),
    "",
    "## Decisions",
    "",
    ...orNone(entries(t.decisions), "None yet."),
    "",
    "## Handoff",
    "",
    ...handoff,
    "",
    "## Git trail",
    "",
    ...(commits.length ? commits.map((c) => `- ${oneLine(c)}`) : ["No commits on this thread yet."]),
    ...(o.trail?.diffStat ? ["", `Uncommitted: ${oneLine(o.trail.diffStat)}`] : []),
    "",
    "## How to continue",
    "",
    "1. Read AGENTS.md in your working directory for your role's rules.",
    "2. Check the board and progress above; continue from the latest progress.",
    '3. Record progress with agt progress <id> "<…>", findings with agt note, doubts with agt question.',
    "",
  ].join("\n");
}
