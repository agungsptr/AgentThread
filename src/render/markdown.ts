import { stringify } from "yaml";
import { DEFAULT_CONFIG, type Config } from "../config/config.ts";
import { displayStatus, isLive, progressBy, type Session, type State, type Thread } from "../state/projection.ts";

export const oneLine = (s: string) => s.replace(/\r?\n+/g, " ").trim();
const cell = (s: string) => oneLine(s).replace(/\|/g, "\\|");
export const clampHeadings = (s: string) => {
  const clamped = s.replace(/^ {0,3}#{1,2}(?=[ \t]|$)/gm, "###");
  const fences = clamped.split("\n").filter((l) => /^ {0,3}(```|~~~)/.test(l)).length;
  return fences % 2 ? `${clamped}\n\`\`\`` : clamped;
};
const orNone = (lines: string[], none: string) => (lines.length ? lines : [none]);

export function renderMain(state: State, config: Config = DEFAULT_CONFIG): string {
  const threads = [...state.threads.values()];
  const rows = threads.map((t) => {
    const done = t.tickets.filter((k) => k.status === "done").length;
    const live = [...state.sessions.values()].filter((s) => s.thread === t.id && isLive(s));
    const coord = live.find((s) => s.role === "coordinator");
    const coordinator = coord ? displayStatus(coord) : "-";
    const workers = live.filter((s) => s.role === "worker").length;
    const limit = t.maxWorkers ?? config.workers.max_workers;
    return `| ${t.id} | ${cell(t.title)} | ${t.type} | ${t.status} | ${done}/${t.tickets.length} | ${t.dependsOn.join(", ") || "-"} | ${coordinator} | ${workers}/${limit} |`;
  });
  const attention = threads.flatMap((t) =>
    t.status === "review" ? [`- ${t.id}: awaiting review`] : t.status === "blocked" ? [`- ${t.id}: blocked`] : [],
  );
  return [
    `# Main Thread — ${oneLine(state.project?.name ?? "")}`,
    "",
    "| ID | Title | Type | Status | Tickets | Depends | Coordinator | Workers |",
    "|----|-------|------|--------|---------|---------|-------------|---------|",
    ...rows,
    "",
    "## Needs user attention",
    "",
    ...orNone(attention, "_Nothing right now._"),
    "",
  ].join("\n");
}

export function renderSub(t: Thread, sessions: Session[] = []): string {
  const frontmatter = stringify({
    id: t.id,
    title: t.title,
    type: t.type,
    status: t.status,
    depends_on: t.dependsOn,
    branch: t.branch,
    worktree: t.worktree,
    tab: t.tab ?? null,
    max_workers: t.maxWorkers ?? null,
    sessions: sessions.map((s) => ({
      id: s.id,
      role: s.role,
      agent: s.agent,
      status: displayStatus(s),
      ...(s.contextTokens !== undefined ? { context_tokens: s.contextTokens } : {}),
      ...(s.ticket ? { ticket: s.ticket } : {}),
      ...(s.pane ? { pane: s.pane } : {}),
    })),
  }).trimEnd();
  const handoff = t.handoff
    ? [...(t.handoff.generated ? ["> Generated by the daemon.", ""] : []), clampHeadings(t.handoff.content.trim())]
    : ["_No handoff yet._"];
  return [
    "---",
    frontmatter,
    "---",
    "",
    "## Goal",
    "",
    clampHeadings(t.goal.trim()) || "_Not set._",
    "",
    "## Acceptance criteria",
    "",
    ...orNone(t.criteria.map((c) => `- [ ] ${oneLine(c)}`), "_None yet._"),
    "",
    "## Context & decisions",
    "",
    ...orNone(t.decisions.map((d) => `- ${d.ts} ${oneLine(d.message)}`), "_None yet._"),
    "",
    "## Progress",
    "",
    ...(t.progress ? [`${t.progress.ts} ${progressBy(t.progress)} ${oneLine(t.progress.message)}`] : ["_None yet._"]),
    ...Object.entries(t.workerProgress).map(([k, p]) => `- ${k} ${p.ts} ${progressBy(p)} ${oneLine(p.message)}`),
    "",
    "## Findings",
    "",
    ...orNone(t.findings.map((d) => `- ${d.ts} ${oneLine(d.message)}`), "_None yet._"),
    "",
    "## Open questions",
    "",
    ...orNone(t.questions.map((d) => `- ${d.ts} ${oneLine(d.message)}`), "_None yet._"),
    "",
    "## Handoff",
    "",
    ...handoff,
    "",
  ].join("\n");
}

export function renderBoard(t: Thread): string {
  return [
    `# Board — ${t.id} ${oneLine(t.title)}`,
    "",
    "| Ticket | Title | Scope | Status | Assignee |",
    "|--------|-------|-------|--------|----------|",
    ...t.tickets.map(
      (k) => `| ${k.id} | ${cell(k.title)} | ${cell(k.scope.join(", "))} | ${k.status} | ${cell(k.assignee ?? "-")} |`,
    ),
    "",
  ].join("\n");
}

export function renderLog(t: Thread): string {
  return [
    `# Log — ${t.id} ${oneLine(t.title)}`,
    "",
    ...t.log.map((e) => {
      const who = e.actor.session ? `${e.actor.role}:${e.actor.session}` : e.actor.role;
      return `- ${e.ts} [${who}] ${oneLine(e.message)}`;
    }),
    "",
  ].join("\n");
}
