import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Config } from "../config/config.ts";
import { ensureLocalRunIgnored } from "../project/init.ts";
import { hasServices } from "./target.ts";

/** The first line of every file agt generates; a Makefile or MAKEFILE.md without it is the user's and is never touched. */
export const MAKEFILE_MARKER = "# generated by agt: edit .agentthread/config.yaml, not this file";
export const MAKEFILE_MD_MARKER = "<!-- generated by agt: edit .agentthread/config.yaml, not this file -->";

/**
 * The targets, shared by agt.mk and MAKEFILE.md. Make variables are user input: every one reaches the shell through
 * `q`, which single-quotes it, so a value is always one argv word.
 */
export function renderMk(): string {
  return `${MAKEFILE_MARKER}
# Included by the generated Makefile; a project-owned Makefile can \`include .agentthread/agt.mk\` instead.
AGT ?= agt

# q: one shell word, single-quoted (a ' becomes '\\'').
q = '$(subst ','\\'',$(1))'
task_flag = $(if $(TASK),--task $(call q,$(TASK)))
only_flag = $(if $(ONLY),--only $(call q,$(ONLY)))

.PHONY: help start stop restart status logs wt-new

help:
	@printf '%s\\n' \\
	  'start   [TASK=<slug>] [ONLY=a,b]            start the services (TASK: that task worktrees; default: the recorded target)' \\
	  'stop    [ONLY=a,b]                          stop the services' \\
	  'restart [TASK=<slug>] [ONLY=a,b]            stop, then start, in the background (progress: .local-run/restart.log)' \\
	  'status                                      service table and the stack lock' \\
	  'logs    SVC=<name>                          tail a service log' \\
	  'wt-new  TASK=<slug> REPOS=a,b [SRC=<branch>]  add worktrees to the thread of that task'

start:
	@$(AGT) stack start $(task_flag) $(only_flag)

stop:
	@$(AGT) stack stop $(only_flag)

restart:
	@$(AGT) stack restart $(task_flag) $(only_flag)

status:
	@$(AGT) stack status

logs:
	@$(if $(SVC),,$(error SVC is required: make logs SVC=<service>))$(AGT) stack logs $(call q,$(SVC))

wt-new:
	@$(if $(TASK),,$(error TASK is required: make wt-new TASK=<slug> REPOS=a,b [SRC=<branch>]))$(if $(REPOS),,$(error REPOS is required: make wt-new TASK=<slug> REPOS=a,b [SRC=<branch>]))set -f; \\
	thread=$$($(AGT) thread find --task $(call q,$(TASK))) || exit 1; \\
	for r in $$(printf '%s' $(call q,$(REPOS)) | tr ',' ' '); do \\
	  $(AGT) worktree add "$$thread" "$$r" $(if $(SRC),--from $(call q,$(SRC))) || exit 1; \\
	done
`;
}

export function renderMakefile(): string {
  return `${MAKEFILE_MARKER}
# Thin wrapper around the agt stack commands; the targets live in .agentthread/agt.mk (see MAKEFILE.md).
.DEFAULT_GOAL := help
-include .agentthread/agt.mk

# A fresh clone has no .agentthread/agt.mk (it is not committed): every target says how to get it.
ifeq ($(wildcard .agentthread/agt.mk),)
.PHONY: help start stop restart status logs wt-new
help start stop restart status logs wt-new:
	@echo "this Makefile needs agt: run agt init in $(CURDIR)" >&2; exit 1
endif
`;
}

const cell = (v: string | number | undefined) => (v === undefined || v === "" ? "-" : String(v).replace(/\|/g, "\\|"));

export function renderMakefileMd(config: Config): string {
  const services = Object.entries(config.workspace.services ?? {});
  const rows = services.map(
    ([n, s]) =>
      `| ${n} | ${s.repo} | ${cell(s.dir)} | \`${cell(s.start)}\` | ${cell(s.port)} | ${cell(s.health ?? (s.port !== undefined ? `tcp:${s.port}` : undefined))} | ${s.migrate ? `\`${cell(s.migrate)}\`` : "-"} | ${s.after?.length ? s.after.join(", ") : "-"} | ${s.enabled === false ? "no" : "yes"} |`,
  );
  return `${MAKEFILE_MD_MARKER}
# Makefile targets

Generated from \`.agentthread/config.yaml\`. Edit the config (\`workspace.services\`), not this file. If you keep your own Makefile, add \`include .agentthread/agt.mk\` to it: agt keeps that file current with the same targets.

## Targets

| target | what it does |
| --- | --- |
| \`make start\` | \`agt stack start\`: install, migrate when the stamp changed, start each service in order and wait until healthy |
| \`make stop\` | \`agt stack stop\` |
| \`make restart\` | \`agt stack restart\`: stop then start, detached; progress in \`.local-run/restart.log\` |
| \`make status\` | \`agt stack status\`: service table and the stack lock |
| \`make logs SVC=<name>\` | \`agt stack logs <name>\` |
| \`make wt-new TASK=<slug> REPOS=a,b [SRC=<branch>]\` | \`agt worktree add\` for each repo on the thread of that task; if no thread has the task it says how to create one (\`agt thread new "<title>" --type feature --task <slug>\`) and fails |
| \`make help\` | list the targets |

## Variables

- \`TASK\`: a task slug; \`start\` and \`restart\` run that task's worktrees (default: the recorded target, else the main checkout). \`wt-new\` takes the task whose thread gets the worktrees.
- \`ONLY\`: comma-separated services for \`start\`, \`stop\` and \`restart\`.
- \`SVC\`: the service for \`logs\`.
- \`REPOS\`: comma-separated repos for \`wt-new\`. \`SRC\`: the source branch for \`wt-new\` (\`--from\`).
- \`AGT\`: the agt command (default \`agt\`).

Values are passed to agt as single arguments (quoted), never interpreted by the shell.

## Services

${services.length ? `| service | repo | dir | start | port | health | migrate | after | enabled |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n${rows.join("\n")}` : "No services are configured (`workspace.services`)."}

## .local-run/

At the project root, git-ignored:

- \`<service>.pid\` and \`<service>.log\`: the running process and its output.
- \`<service>.stamp\`: the checkout state at the last install/migrate; they rerun when it changes.
- \`task\`: the current target, a task slug or \`main\`.
- \`restart.log\`: output of the last \`make restart\`.
`;
}

/** Writes a generated file unless the path holds a file that is not agt's (no marker on its first line). */
function writeOwned(file: string, marker: string, content: string): boolean {
  if (existsSync(file) && readFileSync(file, "utf8").split("\n", 1)[0] !== marker) return false;
  writeFileSync(file, content);
  return true;
}

/**
 * Regenerates `.agentthread/agt.mk` always, and `Makefile` and `MAKEFILE.md` at the root when absent or agt's own.
 * Only for projects with services. Returns the files written.
 */
export function writeStackMakefiles(root: string, config: Config): string[] {
  if (!hasServices(config)) return [];
  ensureLocalRunIgnored(root);
  const written: string[] = [];
  mkdirSync(join(root, ".agentthread"), { recursive: true });
  writeFileSync(join(root, ".agentthread", "agt.mk"), renderMk());
  written.push(".agentthread/agt.mk");
  if (writeOwned(join(root, "Makefile"), MAKEFILE_MARKER, renderMakefile())) written.push("Makefile");
  if (writeOwned(join(root, "MAKEFILE.md"), MAKEFILE_MD_MARKER, renderMakefileMd(config))) written.push("MAKEFILE.md");
  return written;
}
