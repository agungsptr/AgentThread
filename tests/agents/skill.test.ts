import { describe, expect, test } from "bun:test";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { DEFAULT_CONFIG, type Config } from "../../src/config/config.ts";
import { MARKER, refreshRootSkill, skillText, writeSkill } from "../../src/agents/skill.ts";
import { parse } from "yaml";
import { writeAgentsFiles, writeAgentsFilesAsync } from "../../src/agents/agents-md.ts";
import { addWorktree } from "../../src/project/git.ts";
import { initCommand } from "../../src/project/setup.ts";
import { isolatedConfigHome, tempRepo } from "../helpers.ts";

function git(dir: string, ...args: string[]): string {
  const r = Bun.spawnSync(["git", "-C", dir, ...args], { stdout: "pipe", stderr: "pipe" });
  if (r.exitCode !== 0) throw new Error(`git ${args.join(" ")}: ${r.stderr.toString()}`);
  return r.stdout.toString();
}

const HOME = isolatedConfigHome();
const ENV = { ...process.env, HOME, XDG_CONFIG_HOME: join(HOME, "xdg"), GIT_CONFIG_GLOBAL: join(HOME, "gitconfig"), GIT_CONFIG_NOSYSTEM: "1" };
const REL = ".claude/skills/agt/SKILL.md";
const NOT_GENERATED = `agt: ${REL} is not generated by agt; leaving it alone`;
const off: Config = { ...DEFAULT_CONFIG, agents: { ...DEFAULT_CONFIG.agents, skill: false } };

const FRONTMATTER = [
  "---",
  "name: agt",
  "description: \"Use when working in an AgentThread project (AGT_ROLE is set, or the project has .agentthread/) — how to use the agt CLI for your role (main, coordinator or worker): threads, tickets, workers, notes, questions, handoffs and recovery.\"",
  "---",
].join("\n");

function worktreeOf(root: string) {
  const wt = join(root, ".worktrees", "001-x");
  addWorktree(root, "thread/001-x", wt);
  return wt;
}

describe("skillText", () => {
  test("frontmatter, marker, then the full guide", () => {
    const s = skillText({ root: "/repo", config: DEFAULT_CONFIG });
    expect(s.startsWith(`${FRONTMATTER}\n${MARKER}\n`)).toBe(true);
    expect(MARKER).toBe("<!-- Generated by agt; do not edit. Regenerated by agt init, agt setup and agt start. -->");
    expect(s).toContain("## Coordinator");
  });
});

describe("frontmatter", () => {
  test("is valid YAML with the exact name and description", () => {
    const block = skillText({ root: "/repo", config: DEFAULT_CONFIG }).split("\n---\n")[0]!.replace(/^---\n/, "");
    const fm = parse(block) as { name: string; description: string };
    expect(fm.name).toBe("agt");
    expect(fm.description).toBe(
      "Use when working in an AgentThread project (AGT_ROLE is set, or the project has .agentthread/) — how to use the agt CLI for your role (main, coordinator or worker): threads, tickets, workers, notes, questions, handoffs and recovery.",
    );
  });
});

describe("writeSkill", () => {
  const opts = (log: (m: string) => void, tracked = false, config: Config = DEFAULT_CONFIG) => ({ root: "/repo", config, tracked, log });
  const dirOf = () => tempRepo();

  test("written, then unchanged", () => {
    const dir = dirOf();
    expect(writeSkill(dir, opts(() => {}))).toBe("written");
    expect(readFileSync(join(dir, REL), "utf8")).toBe(skillText({ root: "/repo", config: DEFAULT_CONFIG }));
    expect(writeSkill(dir, opts(() => {}))).toBe("unchanged");
  });

  test("a stale generated file is rewritten", () => {
    const dir = dirOf();
    mkdirSync(join(dir, ".claude/skills/agt"), { recursive: true });
    writeFileSync(join(dir, REL), `${FRONTMATTER}\n${MARKER}\n\nold\n`);
    expect(writeSkill(dir, opts(() => {}))).toBe("written");
  });

  test("a file without the marker is left alone, with the log line", () => {
    const dir = dirOf();
    mkdirSync(join(dir, ".claude/skills/agt"), { recursive: true });
    writeFileSync(join(dir, REL), "mine\n");
    const logs: string[] = [];
    expect(writeSkill(dir, opts((m) => logs.push(m)))).toBe("skipped");
    expect(readFileSync(join(dir, REL), "utf8")).toBe("mine\n");
    expect(logs).toEqual([NOT_GENERATED]);
  });

  test("tracked: skipped with the log line", () => {
    const dir = dirOf();
    const logs: string[] = [];
    expect(writeSkill(dir, opts((m) => logs.push(m), true))).toBe("skipped");
    expect(existsSync(join(dir, REL))).toBe(false);
    expect(logs).toEqual([NOT_GENERATED]);
  });

  test("agents.skill false: nothing written, no log", () => {
    const dir = dirOf();
    const logs: string[] = [];
    expect(writeSkill(dir, opts((m) => logs.push(m), false, off))).toBe("skipped");
    expect(existsSync(join(dir, REL))).toBe(false);
    expect(logs).toEqual([]);
  });
});

describe("project root", () => {
  test("agt init writes the skill and keeps it out of git status", async () => {
    const root = tempRepo();
    const [ol, oe] = [console.log, console.error];
    console.log = () => {};
    console.error = () => {};
    try {
      expect(await initCommand(root, { ...ENV, AGT_CLAUDE_BIN: "/nonexistent/a", AGT_OPENCODE_BIN: "/nonexistent/b", AGT_CODEX_BIN: "/nonexistent/c", AGT_OMP_BIN: "/nonexistent/d" }, "x", true)).toBe(0);
    } finally {
      [console.log, console.error] = [ol, oe];
    }
    const text = readFileSync(join(root, REL), "utf8");
    expect(text.startsWith(`${FRONTMATTER}\n${MARKER}\n`)).toBe(true);
    expect(text).toContain("## Coordinator");
    expect(git(root, "status", "--porcelain")).not.toContain(".claude");
    expect(readFileSync(join(root, ".git", "info", "exclude"), "utf8").split("\n")).toContain("/.claude/skills/agt/");
  });

  test("refresh twice: unchanged, and the exclude line is added once", () => {
    const root = tempRepo();
    refreshRootSkill(root, ENV, () => {});
    refreshRootSkill(root, ENV, () => {});
    const lines = readFileSync(join(root, ".git", "info", "exclude"), "utf8").split("\n").filter((l) => l === "/.claude/skills/agt/");
    expect(lines.length).toBe(1);
  });

  test("a tracked project skill is left alone, with the log line and no exclude", () => {
    const root = tempRepo();
    mkdirSync(join(root, ".claude/skills/agt"), { recursive: true });
    writeFileSync(join(root, REL), "project's own\n");
    git(root, "add", REL);
    git(root, "commit", "-q", "-m", "skill");
    const logs: string[] = [];
    refreshRootSkill(root, ENV, (m) => logs.push(m));
    expect(readFileSync(join(root, REL), "utf8")).toBe("project's own\n");
    expect(logs).toEqual([NOT_GENERATED]);
    expect(readFileSync(join(root, ".git", "info", "exclude"), "utf8")).not.toContain("/.claude/skills/agt/");
  });

  test("an untracked hand-written file is left alone, with the log line", () => {
    const root = tempRepo();
    mkdirSync(join(root, ".claude/skills/agt"), { recursive: true });
    writeFileSync(join(root, REL), "mine\n");
    const logs: string[] = [];
    refreshRootSkill(root, ENV, (m) => logs.push(m));
    expect(readFileSync(join(root, REL), "utf8")).toBe("mine\n");
    expect(logs).toEqual([NOT_GENERATED]);
  });

  test("agents.skill false: nothing written", () => {
    const root = tempRepo();
    mkdirSync(join(root, ".agentthread"), { recursive: true });
    writeFileSync(join(root, ".agentthread", "config.yaml"), "agents:\n  skill: false\n");
    refreshRootSkill(root, ENV, () => {});
    expect(existsSync(join(root, REL))).toBe(false);
  });
});

describe("worktrees", () => {
  const write = (root: string, wt: string, config: Config, log: (m: string) => void = () => {}) =>
    writeAgentsFiles({ root, worktree: wt, content: "# AgentThread\n", env: ENV, config, log });

  test("the worktree gets the skill; status is clean; a coordinator commit leaves it out", () => {
    const root = tempRepo();
    const wt = worktreeOf(root);
    write(root, wt, DEFAULT_CONFIG);
    expect(readFileSync(join(wt, REL), "utf8")).toBe(skillText({ root, config: DEFAULT_CONFIG }));
    expect(git(wt, "status", "--porcelain")).toBe("");
    writeFileSync(join(wt, "f.txt"), "x\n");
    git(wt, "add", "-A");
    git(wt, "commit", "-q", "-m", "work");
    expect(git(wt, "show", "--name-only", "--format=", "HEAD").trim()).toBe("f.txt");
    // a second write is a no-op for the file
    write(root, wt, DEFAULT_CONFIG);
    expect(git(wt, "status", "--porcelain")).toBe("");
  });

  test("writeAgentsFilesAsync writes the skill and keeps status clean", async () => {
    const root = tempRepo();
    const wt = worktreeOf(root);
    await writeAgentsFilesAsync({ root, worktree: wt, content: "# AgentThread\n", env: ENV, config: DEFAULT_CONFIG, log: () => {} });
    expect(readFileSync(join(wt, REL), "utf8")).toBe(skillText({ root, config: DEFAULT_CONFIG }));
    expect(git(wt, "status", "--porcelain")).toBe("");
  });

  test("a tracked project skill stays as it is, with the log line", () => {
    const root = tempRepo();
    mkdirSync(join(root, ".claude/skills/agt"), { recursive: true });
    writeFileSync(join(root, REL), "project's own\n");
    git(root, "add", REL);
    git(root, "commit", "-q", "-m", "skill");
    const wt = worktreeOf(root);
    const logs: string[] = [];
    write(root, wt, DEFAULT_CONFIG, (m) => logs.push(m));
    expect(readFileSync(join(wt, REL), "utf8")).toBe("project's own\n");
    expect(logs).toContain(NOT_GENERATED);
    expect(git(wt, "status", "--porcelain")).toBe("");
  });

  test("agents.skill false: nothing written", () => {
    const root = tempRepo();
    const wt = worktreeOf(root);
    write(root, wt, off);
    expect(existsSync(join(wt, REL))).toBe(false);
  });
});
